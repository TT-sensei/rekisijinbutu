  function escapeRegExp(value) {
    return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }

  function replaceTextNode(node) {
    const source = node.nodeValue;
    if (!source || !matcher || !matcher.test(source)) {
      if (matcher) matcher.lastIndex = 0;
      return;
    }
    matcher.lastIndex = 0;
    const fragment = document.createDocumentFragment();
    let cursor = 0;
    let match;
    while ((match = matcher.exec(source))) {
      if (match.index > cursor) fragment.appendChild(document.createTextNode(source.slice(cursor, match.index)));
      const ruby = document.createElement("ruby");
      ruby.appendChild(document.createTextNode(match[0]));
      const rt = document.createElement("rt");
      rt.textContent = readings[match[0]];
      ruby.appendChild(rt);
      fragment.appendChild(ruby);
      cursor = match.index + match[0].length;
    }
    if (cursor < source.length) fragment.appendChild(document.createTextNode(source.slice(cursor)));
    if (node.parentNode) node.parentNode.replaceChild(fragment, node);
  }

  function visit(node) {
    if (!node) return;
    if (node.nodeType === Node.TEXT_NODE) {
      const parent = node.parentElement;
      if (!parent || parent.closest("ruby, rt, script, style, textarea, code, noscript")) return;
      replaceTextNode(node);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_NODE) return;
    if (node.nodeType === Node.ELEMENT_NODE && /^(RUBY|RT|SCRIPT|STYLE|TEXTAREA|CODE|NOSCRIPT)$/.test(node.tagName)) return;
    Array.from(node.childNodes).forEach(visit);
  }

